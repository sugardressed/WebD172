// Includes Method: Does the array or string includes the search, eg. below "admin" or "Mongo"

//Checks whether an array contains a value.
const roles = ["student", "editor", "admin"];

console.log(roles.includes("admin"));

//with strings
const title = "Learn MongoDB";

console.log(title.includes("Mongo"));

//OUTPUT:
//true
//true
//Both statements are true.
